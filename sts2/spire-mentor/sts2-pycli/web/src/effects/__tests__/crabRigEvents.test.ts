import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, it, expect } from "vitest";
import * as spine from "@esotericsoftware/spine-webgl";
import { crabRigEventVfx } from "../crabRigEvents";
import type { VfxManifest } from "../manifest";

// The Kaiser Crab's rig-driven VFX (GH #642). Three joins have to hold, and
// none of them is checked by the type system:
//
//   1. the event name against the RIG the workbench actually ships,
//   2. the effect key against the extracted MANIFEST,
//   3. the bone name against the rig's own bone list.
//
// Every one of them is a string typed by hand on one side and generated on the
// other. A typo in any of them fails silently at runtime: no error, just an
// explosion that never draws — which is the exact bug #642 was filed for.

const WEB_ROOT = resolve(__dirname, "../../..");
const ART = resolve(WEB_ROOT, "../../sts2-wiki/site/public/images");

function readJson<T>(rel: string): T | null {
  try {
    return JSON.parse(readFileSync(resolve(ART, rel), "utf8")) as T;
  } catch {
    return null;
  }
}

/** Parse a shipped rig with the real Spine runtime. `null` when the art tree
 *  is absent — the same skip the manifest tests take.
 *
 *  The atlas needs a texture per page or `AtlasAttachmentLoader` throws; none
 *  of the assertions here touch pixels, so a stub is enough. */
function loadRig(base: string): spine.SkeletonData | null {
  try {
    const atlas = new spine.TextureAtlas(readFileSync(resolve(ART, `${base}.atlas`), "utf8"));
    for (const page of atlas.pages) {
      page.setTexture({
        setFilters() {}, setWraps() {}, dispose() {},
        getImage: () => ({ width: 2048, height: 2048 }),
      } as unknown as spine.Texture);
    }
    const bin = new spine.SkeletonBinary(new spine.AtlasAttachmentLoader(atlas));
    return bin.readSkeletonData(new Uint8Array(readFileSync(resolve(ART, `${base}.skel`))));
  } catch {
    return null;
  }
}

describe("crabRigEventVfx", () => {
  it("maps the Crusher's death explosion", () => {
    // `NKaiserCrabBossVfx.OnClawLExplode` (line 387) plays
    // `vfx/monsters/kaiser_crab_boss_explosion` at `%LeftArmExplosionPosition`,
    // whose `bone_name` is `claw_upper`.
    expect(crabRigEventVfx("claw_explode_l")).toEqual({
      effect: "vfx_kaiser_crab_boss_explosion",
      bone: "claw_upper",
    });
  });

  it("draws nothing for the rig's other events", () => {
    // The other nine are real and deliberately unwired (see the module doc).
    // Returning an effect for one would play the explosion on a rocket thrust.
    for (const name of [
      "charge_steam_start", "charge_steam_end",
      "rocket_thrust_start", "rocket_thrust_end", "rocket_throttle",
      "regen_splats_start", "regen_splats_end",
      "death_spit_start", "death_spit_end",
      "plow_chunks_start", "plow_chunks_end",
    ]) {
      expect(crabRigEventVfx(name)).toBeNull();
    }
  });

  it("does not fire on a near-miss name", () => {
    // The C# event is `claw_explode_l`; the C# METHOD is `OnClawLExplode`.
    // Transcribing the method name would compile and never fire.
    expect(crabRigEventVfx("claw_l_explode")).toBeNull();
    expect(crabRigEventVfx("claw_explode_r")).toBeNull();
    expect(crabRigEventVfx("")).toBeNull();
  });

  it("names an event and a bone the shipped crab rig actually has", () => {
    // The join nothing else checks. `claw_explode_l` and `claw_upper` are hand
    // transcribed from the C#; the rig is generated by `extract_rig`. If the
    // rig is re-extracted from a build that renamed either, the explosion
    // stops firing (or fires at the origin) with no error anywhere.
    //
    // Parsed with the real runtime rather than grepped: `strings` on this
    // `.skel` silently omits `left/die` — the clip that carries the event —
    // because the binary interleaves its name with non-printable bytes. That
    // near-miss is why this reads the skeleton properly.
    const rig = loadRig("monster_rigs/kaiser_crab/kaiser_crab");
    if (!rig) return; // art tree absent
    const vfx = crabRigEventVfx("claw_explode_l")!;

    expect(
      new spine.Skeleton(rig).findBone(vfx.bone),
      `crab rig has no bone '${vfx.bone}'`,
    ).toBeTruthy();

    const fired = rig.animations.flatMap((a) =>
      a.timelines.flatMap((t) =>
        t instanceof spine.EventTimeline ? t.events.map((e) => `${a.name}:${e.data.name}`) : [],
      ),
    );
    // Specifically on the CRUSHER's death clip: the game fires this from the
    // left arm dying, and an event that moved to another clip would play the
    // explosion at the wrong moment while still "existing" on the rig.
    expect(fired).toContain(`left/die:${"claw_explode_l"}`);
  });

  it("the explosion rig carries the ember event stage 2 will need", () => {
    // Not consumed yet — the `explosion_slot` particle burst is GH #669. This
    // pins that the extracted rig still carries what that work depends on, so
    // the follow-up does not start by rediscovering it.
    const rig = loadRig(
      "vfx_rigs/vfx_kaiser_crab_boss_explosion/vfx_kaiser_crab_boss_explosion",
    );
    if (!rig) return;
    expect(rig.animations.map((a) => a.name)).toContain("animation");
    expect(rig.slots.map((s) => s.name)).toContain("explosion_slot");
    const fired = rig.animations.flatMap((a) =>
      a.timelines.flatMap((t) =>
        t instanceof spine.EventTimeline ? t.events.map((e) => e.data.name) : [],
      ),
    );
    expect(fired).toContain("left_embers_start");
  });

  it("names an effect the extracted manifest actually carries", () => {
    const m = readJson<VfxManifest>("vfx/manifest.json");
    if (!m) return; // art tree absent (see manifestShape.test.ts's header)
    const vfx = crabRigEventVfx("claw_explode_l")!;
    const entry = m.effects[vfx.effect];
    expect(entry, `manifest has no '${vfx.effect}'`).toBeDefined();
    expect(entry.kind).toBe("spine");
  });
});
