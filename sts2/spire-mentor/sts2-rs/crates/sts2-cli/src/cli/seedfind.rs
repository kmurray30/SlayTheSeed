//! `sts2-cli seedfind` — search seeds for specific run-content combinations.
//!
//! Answers requests of the shape "find me a seed that offers *these* relics
//! from the act-2 boss Ancient, has *this* event in the act pool, and surfaces
//! *this* card as a reward N times" (GH #297). The finder enumerates seeds in
//! parallel and keeps those whose generated content satisfies a declarative
//! [`Spec`] loaded from a TOML file.
//!
//! ## Two tiers of predicate
//!
//! Content in STS2 splits cleanly into what a seed fixes on its own and what
//! only materialises once a *path* is walked (see the run-RNG notes in
//! `sts2_core::run_rng_set`):
//!
//! * **Seed-alone (exact, cheap).** Neow offers, per-act encounter/elite/boss
//!   identities, the shuffled event *pool*, and the Ancient (boss-relic)
//!   offers are all pre-rolled at run start off isolated / `up_front` streams.
//!   These are computed with no combat, from a freshly initialised
//!   [`RunManager`], and matched exactly.
//! * **Path-dependent (driven, best-effort).** Which concrete card a reward
//!   screen shows, which relic a pickup yields, and which event a `?` resolves
//!   to depend on the shared `rewards` cursor + pity counters + the visited-set
//!   cursor, i.e. on how the run was actually played. These predicates are
//!   evaluated by *driving* the run headlessly (invincible, so combats always
//!   complete) over one or more random paths and collecting everything that
//!   surfaced. A miss means "not found on the sampled path(s)", not "impossible
//!   for this seed" — raise `--paths-per-seed` to widen the sample.
//!
//! A seed matches iff **every** predicate in the spec holds. Seed-alone
//! predicates are checked first as a cheap pre-filter; the (expensive) drive
//! only runs when a seed clears them and the spec actually has driven
//! predicates.

