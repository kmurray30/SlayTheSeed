#!/usr/bin/env python3
"""Re-vendor ``localization_eng/`` from a game build's ``.pck``.

``localization_eng/`` is the game's English localization, and ~64 places in the
monorepo read it for display text. It must describe the build the engine
simulates (``workbench.localization._ENGINE_WIKI_VERSION``): until 2026-08-24 it
was a v0.103.2 dump while everything else — the decomp, the vendored headless
``lib/sts2.dll``, the wiki manifest — was already v0.107.1.

**The result is a MERGE, not a raw dump.** The pinned build wins every key it
has; keys only the older build had are RETAINED, because the engine still
implements content the game removed (Follow Through, Grapple, Prepare,
Doormaker, Medical Kit, Blade of Ink, Hunger of the Void, …). 92 keys came
across that way at the v0.103.2 -> v0.107.1 bump. Dropping them would blank
those items' names and rules text in the workbench.

Usage::

    uv run python scripts/vendor_localization.py \\
        ../sts2_binaries/v0.107.1/SlayTheSpire2.pck --version v0.107.1

**Per-version copies (GH #801).** ``localization_eng/`` is the DEFAULT build's
(v0.107.1) dump; every other supported build gets a sibling
``localization_eng_<ver>/`` (e.g. ``localization_eng_v0.111.0/``), read through
``workbench.localization.loc_dir_for``. Seed it from the default copy so the
merge keeps the keys only the older build had, then vendor over it. An
already-extracted ``localization/eng`` tree (``sts2-wiki/extracted/<ver>/``)
can stand in for the pck::

    cp -r localization_eng localization_eng_v0.111.0
    uv run python scripts/vendor_localization.py \\
        ../sts2-wiki/extracted/v0.111.0/localization/eng --extracted \\
        --version v0.111.0 --out localization_eng_v0.111.0

Re-run it when the engine pin moves, and move ``_ENGINE_WIKI_VERSION`` in the
same commit.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
_DEFAULT_OUT = _REPO_ROOT / "localization_eng"
_WIKI = _REPO_ROOT.parent / "sts2-wiki"


def _extract(pck: Path, dest: Path) -> Path:
    """Unpack the pck's ``localization/eng`` tree with the wiki's extractor."""
    subprocess.run(
        [
            sys.executable,
            "-m",
            "scripts.extract_pck",
            str(pck),
            str(dest),
            "--prefix",
            "localization/eng",
        ],
        cwd=_WIKI,
        check=True,
    )
    eng = dest / "localization" / "eng"
    if not eng.is_dir():
        raise SystemExit(f"no localization/eng under {dest} — is {pck} a game pck?")
    return eng


def vendor(pck: Path, out_dir: Path, *, version: str, extracted: bool = False) -> dict[str, int]:
    """Merge the pck's tables over ``out_dir`` in place. Returns a per-kind tally.

    With ``extracted``, ``pck`` is an already-unpacked ``localization/eng``
    directory rather than a ``.pck``.
    """
    stats = {"tables": 0, "new_tables": 0, "changed_keys": 0, "added_keys": 0, "retained_keys": 0}
    out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="sts2loc") as tmp:
        eng = pck if extracted else _extract(pck, Path(tmp))
        for src in sorted(eng.iterdir()):
            # The pck also carries ``patch_notes/`` — 100+ markdown files of
            # release notes. Nothing here reads them and they are bulky game
            # prose, so only the flat ``<KEY>: <string>`` tables come across.
            if src.is_dir() or src.suffix != ".json":
                continue
            stats["tables"] += 1
            new: dict[str, str] = json.loads(src.read_text(encoding="utf-8"))
            dst = out_dir / src.name
            old: dict[str, str] = (
                json.loads(dst.read_text(encoding="utf-8")) if dst.is_file() else {}
            )
            if not old:
                stats["new_tables"] += 1
            stats["changed_keys"] += sum(1 for k, v in new.items() if k in old and old[k] != v)
            stats["added_keys"] += sum(1 for k in new if k not in old)
            retained = {k: v for k, v in old.items() if k not in new}
            stats["retained_keys"] += len(retained)
            merged = dict(new)
            merged.update(retained)
            # Match the existing files byte-for-byte in shape: 2-space indent,
            # sorted keys, real UTF-8, no trailing newline — so a re-vendor
            # diffs as content only.
            dst.write_text(
                json.dumps({k: merged[k] for k in sorted(merged)}, indent=2, ensure_ascii=False),
                encoding="utf-8",
            )
    (out_dir / "BUILD.txt").write_text(
        f"{version}\n\nGenerated by scripts/vendor_localization.py. The pinned build wins every\n"
        "key it ships; keys only an older build had are retained, for content the\n"
        "engine still implements after the game removed it.\n",
        encoding="utf-8",
    )
    return stats


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pck", type=Path, help="Path to the build's SlayTheSpire2.pck")
    parser.add_argument(
        "--extracted",
        action="store_true",
        help="PCK is an already-extracted localization/eng directory",
    )
    parser.add_argument("--version", required=True, help='Build tag to record, e.g. "v0.107.1"')
    parser.add_argument("--out", type=Path, default=_DEFAULT_OUT, help="localization_eng/ dir")
    args = parser.parse_args(argv)
    stats = vendor(args.pck, args.out, version=args.version, extracted=args.extracted)
    print(
        f"{args.version}: {stats['tables']} tables ({stats['new_tables']} new), "
        f"{stats['changed_keys']} keys changed, {stats['added_keys']} added, "
        f"{stats['retained_keys']} retained from the previous build",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
